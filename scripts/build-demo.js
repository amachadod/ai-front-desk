// npm run build:demo
// Copies the real triage code into docs/lib/ (GitHub Pages only serves docs/) and writes docs/data.js,
// so the demo page runs the same rules as the tests, in the browser, with no server.
import { writeFileSync, mkdirSync, copyFileSync } from "node:fs";
import { loadHub } from "../src/config.js";
import { triageAll } from "../src/triage.js";
import { dashboard } from "../src/metrics.js";
import { parsePrompts } from "../src/kit.js";
import { sample } from "./data.js";

const hub = loadHub();
const { requests, usage, promptsMd } = sample();
mkdirSync(new URL("../docs/lib/", import.meta.url), { recursive: true });
for (const f of ["text.js", "triage.js", "approval.js", "metrics.js", "kit.js"]) copyFileSync(new URL(`../src/${f}`, import.meta.url), new URL(`../docs/lib/${f}`, import.meta.url));
const data = {
  hub: { name: hub.name, tagline: hub.tagline, company: hub.company, companyNote: hub.companyNote, duplicateThreshold: hub.duplicateThreshold, tools: hub.tools, teams: hub.teams },
  requests,
  cards: triageAll(requests, { tools: hub.tools, threshold: hub.duplicateThreshold }),
  usage,
  dashboard: dashboard(usage),
  prompts: parsePrompts(promptsMd),
};
writeFileSync(new URL("../docs/data.js", import.meta.url), `// Generated by scripts/build-demo.js. Do not edit by hand. All data is fictional / illustrative sample data.\nwindow.FRONTDESK = ${JSON.stringify(data)};\n`);
console.log(`Wrote docs/data.js (${requests.length} requests, ${data.prompts.length} prompts) and copied the rules to docs/lib/.`);
